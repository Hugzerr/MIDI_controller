void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin){
  // On rising edge
  // Switch statement
  switch (GPIO_Pin) {
  case EXTI1_Pin:
    if(HAL_GPIO_ReadPin(GPIOD, EXTI2_Pin) == GPIO_PIN_RESET){
        encoders[0].counter++;
      }
      else {
        encoders[0].counter--;
      }
    break;
  case EXTI2_Pin:
    if(HAL_GPIO_ReadPin(GPIOD, EXTI1_Pin) == GPIO_PIN_RESET){
      encoders[0].counter--;
    }
    else {
      encoders[0].counter++;
    }
    break;
  case EXTI3_Pin:
    if(HAL_GPIO_ReadPin(GPIOD, EXTI4_Pin) == GPIO_PIN_RESET){
        encoders[1].counter++;
      }
      else {
        encoders[1].counter--;
      }
    break;
  case EXTI4_Pin:
    if(HAL_GPIO_ReadPin(GPIOD, EXTI3_Pin) == GPIO_PIN_RESET){
      encoders[1].counter--;
    }
    else {
      encoders[1].counter++;
    }
    break;
  case EXTI5_Pin:
    if(HAL_GPIO_ReadPin(GPIOD, EXTI6_Pin) == GPIO_PIN_RESET){
        encoders[2].counter++;
      }
      else {
        encoders[2].counter--;
      }
    break;
  case EXTI6_Pin:
    if(HAL_GPIO_ReadPin(GPIOD, EXTI5_Pin) == GPIO_PIN_RESET){
      encoders[2].counter--;
    }
    else {
      encoders[2].counter++;
    }
    break;
  default:
      break;
  }
  return;
}

